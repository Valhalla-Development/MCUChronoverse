export const chronology: readonly TimelineEntry[] = curatedChronology.map((entry) => {
    const metadata = metadataBySlug[entry.slug];
    const mergedEntry = {
        ...(metadata?.status === "resolved" ? metadata.source : null),
        ...entry,
    };

    const missingFields = requiredMetadataFields.filter(
        (field) => mergedEntry[field] === undefined
    );
    if (missingFields.length > 0 && process.env.TIMELINE_ALLOW_INCOMPLETE_METADATA !== "1") {
        throw new Error(`Missing enriched metadata for ${entry.slug}: ${missingFields.join(", ")}`);
    }

    return mergedEntry as TimelineEntry;
});

export interface ChronologyIssue {
    message: string;
    slug: string;
}

export function validateChronology(entries: readonly TimelineEntry[]): ChronologyIssue[] {
    const issues: ChronologyIssue[] = [];
    const orders = new Set<number>();
    const slugs = new Set<string>();

    for (const entry of entries) {
        if (orders.has(entry.chronologyOrder)) {
            issues.push({
                message: `Duplicate chronology order ${entry.chronologyOrder}`,
                slug: entry.slug,
            });
        }
        if (slugs.has(entry.slug)) {
            issues.push({ message: "Duplicate slug", slug: entry.slug });
        }
        if (Number.isNaN(Date.parse(entry.releaseDate))) {
            issues.push({ message: "Invalid release date", slug: entry.slug });
        }
        orders.add(entry.chronologyOrder);
        slugs.add(entry.slug);
    }

    return issues;
}

const chronologyIssues = validateChronology(chronology);

if (chronologyIssues.length > 0) {
    throw new Error(`Invalid chronology data: ${JSON.stringify(chronologyIssues)}`);
}
